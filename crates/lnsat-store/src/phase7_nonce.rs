fn validate_stored_nonce(
    connection: &Connection,
    nonce: StoredNonce,
) -> Result<StoredNonce, Phase7PersistenceErrorV1> {
    validate_nonce_scope(&nonce.project_ref, &nonce.resource_ref, &nonce.nonce_id)
        .map_err(|_| Phase7PersistenceErrorV1::EvidenceDrift)?;
    if !valid_prefixed_id(&nonce.audit_binding_id, "p7a_")
        || !valid_prefixed_id(&nonce.authorization_attempt_id, "aat_")
        || nonce.entity_created_at != nonce.issued_at
        || nonce.audit_event_kind != "nonce_state_recorded"
        || nonce.audit_authority_effect != "none"
        || nonce.audit_recorded_at != nonce.issued_at
        || nonce.audit_binding_id
            != identifier("p7a_", NONCE_AUDIT_ID_DOMAIN, &[nonce.nonce_id.as_bytes()])
        || nonce_record_digest(&nonce) != nonce.stored_record_digest
    {
        return Err(Phase7PersistenceErrorV1::EvidenceDrift);
    }
    let attempt = read_validated_attempt_by_id(
        connection,
        &nonce.project_ref,
        &nonce.resource_ref,
        &nonce.authorization_attempt_id,
    )?
    .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    validate_nonce_window(&nonce, &attempt)?;
    let expected_nonce_id = identifier("non_", NONCE_ID_DOMAIN, &[nonce.nonce_digest.as_slice()]);
    if nonce.nonce_id != expected_nonce_id || nonce.binding_digest != attempt.binding_digest {
        return Err(Phase7PersistenceErrorV1::EvidenceDrift);
    }
    validate_nonce_events(&nonce)?;
    Ok(nonce)
}

pub(super) fn read_validated_nonce_by_id(
    connection: &Connection,
    project_ref: &str,
    resource_ref: &str,
    nonce_id: &str,
) -> Result<Option<Phase7AuthorizationNonceRecordV1>, Phase7PersistenceErrorV1> {
    let validated = select_nonce_by_id(connection, project_ref, resource_ref, nonce_id)?
        .map(|stored| validate_stored_nonce(connection, stored))
        .transpose()?;
    validated
        .map(|nonce| {
            let issued_at = nonce.issued_at.clone();
            nonce_public_record(&nonce, &issued_at)
        })
        .transpose()
}

fn validate_nonce_window(
    nonce: &StoredNonce,
    attempt: &Phase7AuthorizationAttemptRecordV1,
) -> Result<(), Phase7PersistenceErrorV1> {
    let issued = canonical_utc_timestamp_millis_v1(&nonce.issued_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let expires = canonical_utc_timestamp_millis_v1(&nonce.expires_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let requested = canonical_utc_timestamp_millis_v1(&attempt.requested_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let attempt_expires = canonical_utc_timestamp_millis_v1(&attempt.expires_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let hard_cap = issued
        .checked_add(PHASE7_NONCE_TTL_MILLIS_V1)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    if issued < requested
        || issued >= attempt_expires
        || expires != hard_cap.min(attempt_expires)
        || expires <= issued
    {
        return Err(Phase7PersistenceErrorV1::EvidenceDrift);
    }
    Ok(())
}

fn validate_nonce_events(nonce: &StoredNonce) -> Result<(), Phase7PersistenceErrorV1> {
    if !(nonce.events.len() == 1 || nonce.events.len() == 2) {
        return Err(Phase7PersistenceErrorV1::EvidenceDrift);
    }
    let first = &nonce.events[0];
    if first.state != "active"
        || first.state_sequence != 1
        || first.prior_state_event_id.is_some()
        || first.prior_state_sequence.is_some()
        || first.effective_at != nonce.issued_at
    {
        return Err(Phase7PersistenceErrorV1::EvidenceDrift);
    }
    validate_nonce_event(nonce, first)?;
    if let Some(terminal) = nonce.events.get(1) {
        let terminal_millis = canonical_utc_timestamp_millis_v1(&terminal.effective_at)
            .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
        let issued_millis = canonical_utc_timestamp_millis_v1(&nonce.issued_at)
            .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
        let expires_millis = canonical_utc_timestamp_millis_v1(&nonce.expires_at)
            .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
        if terminal.state_sequence != 2
            || terminal.prior_state_event_id.as_deref() != Some(first.state_event_id.as_str())
            || terminal.prior_state_sequence != Some(1)
            || !matches!(terminal.state.as_str(), "cancelled" | "expired")
            || terminal_millis < issued_millis
            || (terminal.state == "cancelled" && terminal_millis >= expires_millis)
            || (terminal.state == "expired" && terminal.effective_at != nonce.expires_at)
        {
            return Err(Phase7PersistenceErrorV1::EvidenceDrift);
        }
        validate_nonce_event(nonce, terminal)?;
    }
    Ok(())
}

fn validate_nonce_event(
    nonce: &StoredNonce,
    event: &StoredNonceStateEvent,
) -> Result<(), Phase7PersistenceErrorV1> {
    let expected_event_id = nonce_state_event_id(nonce, &event.state, event.state_sequence);
    let expected_audit_id = identifier(
        "p7a_",
        NONCE_STATE_AUDIT_ID_DOMAIN,
        &[expected_event_id.as_bytes()],
    );
    let expected_effect = if event.state == "active" {
        "nonce_active"
    } else {
        "none"
    };
    if event.state_event_id != expected_event_id
        || event.audit_binding_id != expected_audit_id
        || event.project_ref != nonce.project_ref
        || event.resource_ref != nonce.resource_ref
        || event.target_entity_id != nonce.nonce_id
        || event.target_entity_kind != "authorization_nonce"
        || event.entity_created_at != event.effective_at
        || event.audit_event_kind != "nonce_state_recorded"
        || event.audit_authority_effect != expected_effect
        || event.audit_recorded_at != event.effective_at
        || nonce_state_digest(nonce, event) != event.state_digest
        || nonce_state_record_digest(event) != event.stored_record_digest
    {
        return Err(Phase7PersistenceErrorV1::EvidenceDrift);
    }
    Ok(())
}

fn materialize_expiry_if_needed(
    transaction: &Transaction<'_>,
    nonce: StoredNonce,
    checked_at: &str,
) -> Result<(StoredNonce, bool), Phase7PersistenceErrorV1> {
    let checked = canonical_utc_timestamp_millis_v1(checked_at)
        .ok_or(Phase7PersistenceErrorV1::ClockRejected)?;
    let issued = canonical_utc_timestamp_millis_v1(&nonce.issued_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let latest = nonce
        .events
        .last()
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let latest_time = canonical_utc_timestamp_millis_v1(&latest.effective_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    if checked < issued || checked < latest_time {
        return Err(Phase7PersistenceErrorV1::ClockRejected);
    }
    let expires = canonical_utc_timestamp_millis_v1(&nonce.expires_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    if latest.state != "active" || checked < expires {
        return Ok((nonce, false));
    }
    insert_nonce_state_event(
        transaction,
        &nonce,
        "expired",
        &nonce.expires_at,
        Some(latest),
    )?;
    let reloaded = select_nonce_by_id(
        transaction,
        &nonce.project_ref,
        &nonce.resource_ref,
        &nonce.nonce_id,
    )?
    .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    Ok((validate_stored_nonce(transaction, reloaded)?, true))
}

fn nonce_public_record(
    nonce: &StoredNonce,
    checked_at: &str,
) -> Result<Phase7AuthorizationNonceRecordV1, Phase7PersistenceErrorV1> {
    let checked = canonical_utc_timestamp_millis_v1(checked_at)
        .ok_or(Phase7PersistenceErrorV1::ClockRejected)?;
    let expires = canonical_utc_timestamp_millis_v1(&nonce.expires_at)
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let latest = nonce
        .events
        .last()
        .ok_or(Phase7PersistenceErrorV1::EvidenceDrift)?;
    let state_sequence = u32::try_from(latest.state_sequence)
        .map_err(|_| Phase7PersistenceErrorV1::EvidenceDrift)?;
    Ok(Phase7AuthorizationNonceRecordV1 {
        nonce_id: nonce.nonce_id.clone(),
        audit_binding_id: nonce.audit_binding_id.clone(),
        project_ref: nonce.project_ref.clone(),
        resource_ref: nonce.resource_ref.clone(),
        authorization_attempt_id: nonce.authorization_attempt_id.clone(),
        binding_digest: nonce.binding_digest,
        nonce_digest: nonce.nonce_digest,
        issued_at: nonce.issued_at.clone(),
        expires_at: nonce.expires_at.clone(),
        state_event_id: latest.state_event_id.clone(),
        state_audit_binding_id: latest.audit_binding_id.clone(),
        state_sequence,
        state: latest.state.clone(),
        state_effective_at: latest.effective_at.clone(),
        active: latest.state == "active" && checked < expires,
    })
}

fn insert_nonce_state_event(
    transaction: &Transaction<'_>,
    nonce: &StoredNonce,
    state: &str,
    effective_at: &str,
    prior: Option<&StoredNonceStateEvent>,
) -> Result<(), Phase7PersistenceErrorV1> {
    let state_sequence = prior.map_or(1, |event| event.state_sequence + 1);
    let state_event_id = nonce_state_event_id(nonce, state, state_sequence);
    let audit_binding_id = identifier(
        "p7a_",
        NONCE_STATE_AUDIT_ID_DOMAIN,
        &[state_event_id.as_bytes()],
    );
    if phase7_entity_exists(transaction, &state_event_id)?
        || audit_binding_exists(transaction, &audit_binding_id)?
    {
        return Err(Phase7PersistenceErrorV1::IdentityConflict);
    }
    let mut event = StoredNonceStateEvent {
        state_event_id,
        audit_binding_id,
        project_ref: nonce.project_ref.clone(),
        resource_ref: nonce.resource_ref.clone(),
        target_entity_id: nonce.nonce_id.clone(),
        target_entity_kind: "authorization_nonce".to_owned(),
        state_sequence,
        state: state.to_owned(),
        prior_state_event_id: prior.map(|event| event.state_event_id.clone()),
        prior_state_sequence: prior.map(|event| event.state_sequence),
        effective_at: effective_at.to_owned(),
        state_digest: [0; 32],
        stored_record_digest: [0; 32],
        entity_created_at: effective_at.to_owned(),
        audit_event_kind: "nonce_state_recorded".to_owned(),
        audit_authority_effect: if state == "active" {
            "nonce_active".to_owned()
        } else {
            "none".to_owned()
        },
        audit_recorded_at: effective_at.to_owned(),
    };
    event.state_digest = nonce_state_digest(nonce, &event);
    event.stored_record_digest = nonce_state_record_digest(&event);
    insert_entity_and_audit(
        transaction,
        &event.state_event_id,
        "phase7_state_event",
        &event.project_ref,
        &event.resource_ref,
        &event.audit_binding_id,
        &event.stored_record_digest,
        "nonce_state_recorded",
        &event.audit_authority_effect,
        &event.effective_at,
    )?;
    transaction
        .execute(
            "INSERT INTO lnsat_phase7_state_events (
                state_event_id, entity_kind, project_ref, resource_ref,
                target_entity_id, target_entity_kind, state_sequence, state,
                prior_state_event_id, prior_state_sequence, effective_at,
                state_digest
             ) VALUES (
                ?1, 'phase7_state_event', ?2, ?3, ?4,
                'authorization_nonce', ?5, ?6, ?7, ?8, ?9, ?10
             )",
            params![
                &event.state_event_id,
                &event.project_ref,
                &event.resource_ref,
                &event.target_entity_id,
                event.state_sequence,
                &event.state,
                &event.prior_state_event_id,
                event.prior_state_sequence,
                &event.effective_at,
                event.state_digest.as_slice(),
            ],
        )
        .map_err(|_| Phase7PersistenceErrorV1::PersistenceFailed)?;
    Ok(())
}

