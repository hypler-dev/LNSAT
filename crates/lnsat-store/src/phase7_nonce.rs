/// Exact raw nonce size generated by server OS CSPRNG.
pub const PHASE7_NONCE_BYTES_V1: usize = 32;
/// Hard nonce lifetime cap. Approval expiry may shorten this window.
pub const PHASE7_NONCE_TTL_SECONDS_V1: u64 = 300;

const PHASE7_NONCE_TTL_MILLIS_V1: u64 = PHASE7_NONCE_TTL_SECONDS_V1 * 1_000;
const NONCE_ID_DOMAIN: &str = "lnsat.phase7.authorization-nonce-id.v1";
const NONCE_AUDIT_ID_DOMAIN: &str = "lnsat.phase7.authorization-nonce-audit-id.v1";
const NONCE_RECORD_DIGEST_DOMAIN: &str = "lnsat.phase7.authorization-nonce-record.v1";
const NONCE_STATE_EVENT_ID_DOMAIN: &str = "lnsat.phase7.nonce-state-event-id.v1";
const NONCE_STATE_AUDIT_ID_DOMAIN: &str = "lnsat.phase7.nonce-state-audit-id.v1";
const NONCE_STATE_DIGEST_DOMAIN: &str = "lnsat.phase7.nonce-state.v1";
const NONCE_STATE_RECORD_DIGEST_DOMAIN: &str = "lnsat.phase7.nonce-state-record.v1";
const LOWER_HEX: &[u8; 16] = b"0123456789abcdef";

/// Exact source scope for server-owned nonce issuance.
///
/// Callers provide no nonce, identifier, timestamp, or expiry.
#[derive(Clone, Copy, Debug)]
pub struct Phase7AuthorizationNonceIssueInputV1<'a> {
    pub project_ref: &'a str,
    pub resource_ref: &'a str,
    pub authorization_attempt_id: &'a str,
}

/// Exact source scope for server-owned nonce cancellation.
#[derive(Clone, Copy, Debug)]
pub struct Phase7AuthorizationNonceCancelInputV1<'a> {
    pub project_ref: &'a str,
    pub resource_ref: &'a str,
    pub nonce_id: &'a str,
}

/// Raw server nonce returned only for first successful issuance.
///
/// Persistence, audit, replay reads, and debug output never expose these bytes.
pub struct Phase7AuthorizationNonceSecretV1 {
    bytes: [u8; PHASE7_NONCE_BYTES_V1],
}

impl Phase7AuthorizationNonceSecretV1 {
    /// Borrows raw nonce bytes for immediate in-process handoff.
    #[must_use]
    pub const fn as_bytes(&self) -> &[u8; PHASE7_NONCE_BYTES_V1] {
        &self.bytes
    }
}

impl fmt::Debug for Phase7AuthorizationNonceSecretV1 {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("Phase7AuthorizationNonceSecretV1(<redacted>)")
    }
}

impl Drop for Phase7AuthorizationNonceSecretV1 {
    fn drop(&mut self) {
        self.bytes.zeroize();
    }
}

