fn select_stored_nonce<P: rusqlite::Params>(
    connection: &Connection,
    predicate: &str,
    parameters: P,
) -> Result<Option<StoredNonce>, Phase7PersistenceErrorV1> {
    let sql = format!(
        "SELECT nonce.nonce_id,
                entity.audit_binding_id,
                nonce.project_ref,
                nonce.resource_ref,
                nonce.authorization_attempt_id,
                nonce.binding_digest,
                nonce.nonce_digest,
                nonce.issued_at,
                nonce.expires_at,
                entity.record_digest,
                entity.created_at,
                audit.event_kind,
                audit.authority_effect,
                audit.recorded_at
         FROM lnsat_authorization_nonces AS nonce
         JOIN lnsat_phase7_entities AS entity
           ON entity.entity_id = nonce.nonce_id
          AND entity.entity_kind = nonce.entity_kind
          AND entity.project_ref = nonce.project_ref
          AND entity.resource_ref = nonce.resource_ref
         JOIN lnsat_phase7_audit_bindings AS audit
           ON audit.audit_binding_id = entity.audit_binding_id
          AND audit.record_id = entity.entity_id
          AND audit.record_family = entity.entity_kind
          AND audit.project_ref = entity.project_ref
          AND audit.resource_ref = entity.resource_ref
          AND audit.record_digest = entity.record_digest
         WHERE {predicate}"
    );
    let base = connection
        .query_row(&sql, parameters, |row| {
            Ok(StoredNonce {
                nonce_id: row.get(0)?,
                audit_binding_id: row.get(1)?,
                project_ref: row.get(2)?,
                resource_ref: row.get(3)?,
                authorization_attempt_id: row.get(4)?,
                binding_digest: blob_32(row.get(5)?)?,
                nonce_digest: blob_32(row.get(6)?)?,
                issued_at: row.get(7)?,
                expires_at: row.get(8)?,
                stored_record_digest: blob_32(row.get(9)?)?,
                entity_created_at: row.get(10)?,
                audit_event_kind: row.get(11)?,
                audit_authority_effect: row.get(12)?,
                audit_recorded_at: row.get(13)?,
                events: Vec::new(),
            })
        })
        .optional()
        .map_err(|_| Phase7PersistenceErrorV1::PersistenceFailed)?;
    let Some(mut nonce) = base else {
        return Ok(None);
    };
    nonce.events = select_nonce_state_events(connection, &nonce.nonce_id)?;
    Ok(Some(nonce))
}

