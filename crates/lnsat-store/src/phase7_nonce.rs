    connection
        .query_row(
            "SELECT 1 FROM lnsat_authorization_nonces
             WHERE project_ref = ?1 AND nonce_digest = ?2",
            params![project_ref, nonce_digest.as_slice()],
            |_| Ok(()),
        )
        .optional()
        .map(|value| value.is_some())
        .map_err(|_| Phase7PersistenceErrorV1::PersistenceFailed)
