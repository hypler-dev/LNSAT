fn nonce_record_digest(nonce: &StoredNonce) -> [u8; 32] {
    digest_fields(
        NONCE_RECORD_DIGEST_DOMAIN,
        &[
            nonce.nonce_id.as_bytes(),
            nonce.audit_binding_id.as_bytes(),
            nonce.project_ref.as_bytes(),
            nonce.resource_ref.as_bytes(),
            nonce.authorization_attempt_id.as_bytes(),
            &nonce.binding_digest,
            &nonce.nonce_digest,
            nonce.issued_at.as_bytes(),
            nonce.expires_at.as_bytes(),
        ],
    )
}

fn nonce_state_event_id(nonce: &StoredNonce, state: &str, state_sequence: i64) -> String {
    let sequence = state_sequence.to_be_bytes();
    identifier(
        "ste_",
        NONCE_STATE_EVENT_ID_DOMAIN,
        &[nonce.nonce_id.as_bytes(), state.as_bytes(), &sequence],
    )
}

fn nonce_state_digest(nonce: &StoredNonce, event: &StoredNonceStateEvent) -> [u8; 32] {
    let sequence = event.state_sequence.to_be_bytes();
    let prior_sequence = event.prior_state_sequence.unwrap_or(0).to_be_bytes();
    digest_fields(
        NONCE_STATE_DIGEST_DOMAIN,
        &[
            nonce.nonce_id.as_bytes(),
            &nonce.binding_digest,
            &nonce.nonce_digest,
            event.state.as_bytes(),
            &sequence,
            event
                .prior_state_event_id
                .as_deref()
                .unwrap_or("")
                .as_bytes(),
            &prior_sequence,
            event.effective_at.as_bytes(),
        ],
    )
}

fn nonce_state_record_digest(event: &StoredNonceStateEvent) -> [u8; 32] {
    let sequence = event.state_sequence.to_be_bytes();
    digest_fields(
        NONCE_STATE_RECORD_DIGEST_DOMAIN,
        &[
            event.state_event_id.as_bytes(),
            event.audit_binding_id.as_bytes(),
            event.project_ref.as_bytes(),
            event.resource_ref.as_bytes(),
            event.target_entity_id.as_bytes(),
            event.target_entity_kind.as_bytes(),
            &sequence,
            event.state.as_bytes(),
            &event.state_digest,
            event.effective_at.as_bytes(),
        ],
    )
}

fn identifier(prefix: &str, domain: &str, fields: &[&[u8]]) -> String {
    let digest = digest_fields(domain, fields);
    let mut encoded = String::with_capacity(prefix.len() + 64);
    encoded.push_str(prefix);
    for byte in digest {
        encoded.push(char::from(LOWER_HEX[usize::from(byte >> 4)]));
        encoded.push(char::from(LOWER_HEX[usize::from(byte & 0x0f)]));
    }
    encoded
}

pub(super) fn canonical_system_time_v1(
    value: SystemTime,
) -> Result<String, Phase7PersistenceErrorV1> {
    let duration = value
        .duration_since(UNIX_EPOCH)
        .map_err(|_| Phase7PersistenceErrorV1::ClockRejected)?;
    let total_millis =
        u64::try_from(duration.as_millis()).map_err(|_| Phase7PersistenceErrorV1::ClockRejected)?;
    let total_seconds = total_millis / 1_000;
    let millisecond = total_millis % 1_000;
    let days = total_seconds / 86_400;
    let seconds_of_day = total_seconds % 86_400;
    let hour = seconds_of_day / 3_600;
    let minute = (seconds_of_day % 3_600) / 60;
    let second = seconds_of_day % 60;
    let (year, month, day) =
        civil_date_from_unix_days_v1(days).ok_or(Phase7PersistenceErrorV1::ClockRejected)?;
    if year > 9_999 {
        return Err(Phase7PersistenceErrorV1::ClockRejected);
    }
    let canonical = format!(
        "{year:04}-{month:02}-{day:02}T{hour:02}:{minute:02}:{second:02}.{millisecond:03}Z"
    );
    canonical_utc_timestamp_millis_v1(&canonical)
        .map(|_| canonical)
        .ok_or(Phase7PersistenceErrorV1::ClockRejected)
}

fn civil_date_from_unix_days_v1(days: u64) -> Option<(u64, u64, u64)> {
    let shifted = i64::try_from(days).ok()?.checked_add(719_468)?;
    let era = shifted / 146_097;
    let day_of_era = shifted - era * 146_097;
    let year_of_era =
        (day_of_era - day_of_era / 1_460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let mut year = year_of_era + era * 400;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let month_prime = (5 * day_of_year + 2) / 153;
    let day = day_of_year - (153 * month_prime + 2) / 5 + 1;
    let month = month_prime + if month_prime < 10 { 3 } else { -9 };
    year += i64::from(month <= 2);
    Some((
        u64::try_from(year).ok()?,
        u64::try_from(month).ok()?,
        u64::try_from(day).ok()?,
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn trusted_system_clock_formats_canonical_utc_and_rejects_pre_epoch() {
        assert_eq!(
            canonical_system_time_v1(UNIX_EPOCH),
            Ok("1970-01-01T00:00:00.000Z".to_owned())
        );
        let leap_day = UNIX_EPOCH
            .checked_add(Duration::from_secs(951_827_696))
            .and_then(|value| value.checked_add(Duration::from_millis(789)))
            .expect("known leap-day timestamp must fit");
        assert_eq!(
            canonical_system_time_v1(leap_day),
            Ok("2000-02-29T12:34:56.789Z".to_owned())
        );
        assert_eq!(
            canonical_system_time_v1(
                UNIX_EPOCH
                    .checked_sub(Duration::from_millis(1))
                    .expect("pre-epoch timestamp must construct")
            ),
            Err(Phase7PersistenceErrorV1::ClockRejected)
        );
    }
}
